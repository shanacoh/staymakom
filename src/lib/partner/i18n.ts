export const PARTNER_TEXTS: Record<PartnerLang, PartnerTexts> = { fr, en, he };

const LOCALES: Record<PartnerLang, string> = { fr: "fr-FR", en: "en-GB", he: "he-IL" };

/** Date lisible dans la langue de l'espace (« 23 octobre 2026 »). Accepte AAAA-MM-JJ ou une date complète. */
export function formatPartnerDate(value: string | null | undefined, lang: PartnerLang, withWeekday = false): string {
  if (!value) return "";
  const date = /^\d{4}-\d{2}-\d{2}$/.test(value) ? new Date(`${value}T12:00:00`) : new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return date.toLocaleDateString(LOCALES[lang], {
    weekday: withWeekday ? "long" : undefined,
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}

export function formatPartnerMonth(month: string, lang: PartnerLang): string {
  return new Date(`${month}-01T12:00:00`).toLocaleDateString(LOCALES[lang], { month: "long", year: "numeric" });
}
